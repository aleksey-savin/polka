export interface IsbnOrigin {
  /** Издательство, если префикс знаком. */
  publisher: string | null
  /** Страна регистрационной группы — известна всегда, когда группа знакома. */
  country: string | null
  /** Короткая подпись для интерфейса. */
  label: string | null
}

/** Только цифры и X: дефисы в ISBN расставлены как попало. */
const digits = (isbn: string) => isbn.replace(/[^0-9Xx]/g, '')

/**
 * Регистрационные группы стран, где книги печатают кириллицей.
 * Латинское название у такого номера — почти всегда транслит каталога.
 */
const CYRILLIC_GROUPS = [
  '5', // Россия и бывший СССР
  '985', // Беларусь
  '966', // Украина
  '617', // Украина (вторая группа)
  '601', // Казахстан
  '9967', // Киргизия
  '9975', // Молдавия
]

/** Номер выдан там, где пишут кириллицей. */
export function isCyrillicRegion(isbn: string | null | undefined): boolean {
  if (!isbn) return false
  const clean = digits(isbn)
  const body =
    clean.length === 13 && clean.startsWith('978')
      ? clean.slice(3)
      : clean.length === 10
        ? clean
        : null
  if (!body) return false
  return CYRILLIC_GROUPS.some((group) => body.startsWith(group))
}

/**
 * Что известно о номере без всяких источников.
 * Для 979-х (новая группа) издателя не определяем — своей таблицы там нет.
 */
export function isbnOrigin(isbn: string | null | undefined): IsbnOrigin {
  const none: IsbnOrigin = { publisher: null, country: null, label: null }
  if (!isbn) return none
  const clean = digits(isbn)
  const body =
    clean.length === 13 && clean.startsWith('978')
      ? clean.slice(3)
      : clean.length === 10
        ? clean
        : null
  if (!body) return none
  if (!body.startsWith('5')) return none

  const rest = body.slice(1)
  // самое длинное совпадение: у «17» и «171…» разные владельцы
  for (let len = 5; len >= 2; len--) {
    const publisher = RU_PUBLISHERS[rest.slice(0, len)]
    if (publisher) {
      return {
        publisher,
        country: 'Россия',
        label: publisher,
      }
    }
  }
  return { publisher: null, country: 'Россия', label: 'Россия' }
}
